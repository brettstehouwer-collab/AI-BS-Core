import sqlite3
import pandas as pd

DB_PATH = r'C:\AI-BS\backend\stehouwer_vault.db'
HTML_OUT = r'C:\StehouwerPublishing.com\website-rebuild\dist\ledger.html'

html_template = """
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>AI-BS God-Mode Salad Ledger</title>
    <script src="https://cdn.tailwindcss.com"></script>
</head>
<body class="bg-gray-900 text-white font-sans p-4">
    <div class="max-w-4xl mx-auto">
        <h1 class="text-3xl font-bold mb-2 text-green-400">AI-BS Salad Ledger</h1>
        <p class="text-gray-400 mb-6">Live God-Mode Hardware Telemetry Dashboard</p>
        
        <div class="overflow-x-auto bg-gray-800 rounded-lg shadow">
            <table class="w-full text-left border-collapse whitespace-nowrap">
                <thead>
                    <tr class="bg-gray-700 text-gray-300 text-sm uppercase tracking-wider">
                        <th class="p-3">End Time</th>
                        <th class="p-3">Job Type</th>
                        <th class="p-3">Duration</th>
                        <th class="p-3">Energy (kWh)</th>
                        <th class="p-3">Data DL/UL</th>
                        <th class="p-3">GPU Peak</th>
                    </tr>
                </thead>
                <tbody id="ledger-body">
                    {table_rows}
                </tbody>
            </table>
        </div>
        <p class="text-xs text-gray-500 mt-4">Auto-generated by AI-BS Sentinel Daemon</p>
    </div>
</body>
</html>
"""

def generate_html():
    conn = sqlite3.connect(DB_PATH)
    try:
        df = pd.read_sql_query("SELECT * FROM salad_job_ledger ORDER BY id DESC LIMIT 50", conn)
        rows = ""
        if df.empty:
            rows = "<tr><td colspan='6' class='p-4 text-center text-gray-400'>No jobs recorded yet. Waiting for first container to finish...</td></tr>"
        else:
            for _, r in df.iterrows():
                rows += f"""
                <tr class="border-b border-gray-700 hover:bg-gray-750 text-sm">
                    <td class="p-3">{r['end_time']}</td>
                    <td class="p-3 font-semibold text-blue-400">{r['job_type']}<br><span class="text-xs text-gray-500">{r['detected_process']}</span></td>
                    <td class="p-3">{r['duration_minutes']:.1f} min</td>
                    <td class="p-3 text-yellow-400">{r['energy_kwh']:.3f} kWh</td>
                    <td class="p-3 text-purple-400">{r['network_dl_mb']:.1f}M / {r['network_ul_mb']:.1f}M</td>
                    <td class="p-3 text-red-400">{r['max_gpu_power_w']}W<br>{r['max_gpu_temp_c']}&deg;C</td>
                </tr>
                """
        
        with open(HTML_OUT, 'w', encoding='utf-8') as f:
            f.write(html_template.replace('{table_rows}', rows))
        print("HTML Ledger generated successfully at", HTML_OUT)
    except Exception as e:
        print(f"Error: {e}")
    finally:
        conn.close()

if __name__ == "__main__":
    generate_html()
