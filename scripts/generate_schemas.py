import json
import os
import glob

SCHEMA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "schemas")
BACKEND_OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "backend", "models", "generated", "schemas.py")
FRONTEND_OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "frontend", "src", "types", "generated", "schemas.ts")
GO_OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "go-core", "pkg", "types", "schemas.go")
RUST_OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "rust_master_worker", "src", "types", "schemas.rs")

TYPE_MAP_PY = {"string": "str", "number": "float", "integer": "int", "boolean": "bool"}
TYPE_MAP_TS = {"string": "string", "number": "number", "integer": "number", "boolean": "boolean"}
TYPE_MAP_GO = {"string": "string", "number": "float64", "integer": "int", "boolean": "bool"}
TYPE_MAP_RS = {"string": "String", "number": "f64", "integer": "i64", "boolean": "bool"}

def generate_all():
    schema_files = glob.glob(os.path.join(SCHEMA_DIR, "*.json"))
    print(f"[SchemaGen] Found {len(schema_files)} schemas in {SCHEMA_DIR}")

    py_lines = ["# AUTO-GENERATED BY scripts/generate_schemas.py - DO NOT EDIT MANUALLY\n", "from pydantic import BaseModel\n", "from typing import Optional\n\n"]
    ts_lines = ["// AUTO-GENERATED BY scripts/generate_schemas.py - DO NOT EDIT MANUALLY\n\n"]
    go_lines = ["// AUTO-GENERATED BY scripts/generate_schemas.py - DO NOT EDIT MANUALLY\npackage types\n\n"]
    rs_lines = ["// AUTO-GENERATED BY scripts/generate_schemas.py - DO NOT EDIT MANUALLY\nuse serde::{Serialize, Deserialize};\n\n"]

    for sf in schema_files:
        with open(sf, "r", encoding="utf-8-sig") as f:
            data = json.load(f)

        name = data.get("title", os.path.splitext(os.path.basename(sf))[0].capitalize() + "Schema")
        props = data.get("properties", {})
        required = data.get("required", [])

        # Python
        py_lines.append(f"class {name}(BaseModel):\n")
        for p_name, p_val in props.items():
            py_type = TYPE_MAP_PY.get(p_val.get("type", "string"), "str")
            if p_name in required:
                py_lines.append(f"    {p_name}: {py_type}\n")
            else:
                py_lines.append(f"    {p_name}: Optional[{py_type}] = None\n")
        py_lines.append("\n")

        # TypeScript
        ts_lines.append(f"export interface {name} {{\n")
        for p_name, p_val in props.items():
            ts_type = TYPE_MAP_TS.get(p_val.get("type", "string"), "string")
            opt = "" if p_name in required else "?"
            ts_lines.append(f"  {p_name}{opt}: {ts_type};\n")
        ts_lines.append("}\n\n")

        # Go
        go_lines.append(f"type {name} struct {{\n")
        for p_name, p_val in props.items():
            go_type = TYPE_MAP_GO.get(p_val.get("type", "string"), "string")
            # Convert snake_case to PascalCase for Go
            go_field = "".join(w.capitalize() for w in p_name.split("_"))
            go_lines.append(f"\t{go_field} {go_type} `json:\"{p_name}\"`\n")
        go_lines.append("}\n\n")

        # Rust
        rs_lines.append("#[derive(Serialize, Deserialize, Debug, Clone)]\n")
        rs_lines.append(f"pub struct {name} {{\n")
        for p_name, p_val in props.items():
            rs_type = TYPE_MAP_RS.get(p_val.get("type", "string"), "String")
            if p_name in required:
                rs_lines.append(f"    pub {p_name}: {rs_type},\n")
            else:
                rs_lines.append(f"    pub {p_name}: Option<{rs_type}>,\n")
        rs_lines.append("}\n\n")

    # Write files
    os.makedirs(os.path.dirname(BACKEND_OUT), exist_ok=True)
    with open(BACKEND_OUT, "w", encoding="utf-8") as f:
        f.writelines(py_lines)

    os.makedirs(os.path.dirname(FRONTEND_OUT), exist_ok=True)
    with open(FRONTEND_OUT, "w", encoding="utf-8") as f:
        f.writelines(ts_lines)

    os.makedirs(os.path.dirname(GO_OUT), exist_ok=True)
    with open(GO_OUT, "w", encoding="utf-8") as f:
        f.writelines(go_lines)

    os.makedirs(os.path.dirname(RUST_OUT), exist_ok=True)
    with open(RUST_OUT, "w", encoding="utf-8") as f:
        f.writelines(rs_lines)

    print(f"[SchemaGen] Generated models for Python, TypeScript, Go, and Rust successfully.")

if __name__ == "__main__":
    generate_all()
