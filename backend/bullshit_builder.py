class ProjectScaffolder:
    def __init__(self, system_tree_path: str):
        self.system_tree_path = system_tree_path
        self.directory_index: Dict[str, List[str]] = {}
        self._parse_system_tree()

    def _parse_system_tree(self):
        print(
            f"[Bullshit Builder - Scaffolder] Parsing system tree file from {self.system_tree_path}..."
        )
        if not os.path.exists(self.system_tree_path):
            print(
                f"[Bullshit Builder - Scaffolder] Warning: Could not find tree file at {self.system_tree_path}."
            )
            return

        ignored_extensions = {
            ".mp4",
            ".mkv",
            ".avi",
            ".png",
            ".jpg",
            ".jpeg",
            ".gif",
            ".exe",
            ".dll",
            ".bin",
            ".iso",
            ".zip",
            ".tar",
            ".gz",
        }

        try:
            with open(
                self.system_tree_path, "r", encoding="utf-8", errors="ignore"
            ) as f:
                for line in f:
                    clean_path = line.strip()
                    if not clean_path or clean_path.startswith("==="):
                        continue

                    _, ext = os.path.splitext(clean_path)
                    if ext.lower() in ignored_extensions:
                        continue

                    base_name = os.path.basename(clean_path).lower()
                    if base_name:
                        if base_name not in self.directory_index:
                            self.directory_index[base_name] = []
                        self.directory_index[base_name].append(clean_path)

            print(
                f"[Bullshit Builder - Scaffolder] Successfully indexed {len(self.directory_index)} unique file/folder targets."
            )
        except Exception as e:
            print(
                f"[Bullshit Builder - Scaffolder] Critical error parsing tree file: {str(e)}"
            )

    def discover_workspace(self, project_keyword: str) -> List[str]:
        matches = []
        keyword = project_keyword.lower()
        print(
            f"[Bullshit Builder - Scaffolder] Searching mapped drives for project context matching: '{keyword}'..."
        )
        for key in self.directory_index.keys():
            if keyword in key:
                matches.extend(self.directory_index[key])
        return list(set(matches))[:50]

    def _discover_and_load_llm_framework(self) -> str:
        print(
            "\n[Bullshit Builder - Scaffolder] Hunting system drives for available LLM provider frameworks..."
        )
        target_frameworks = ["langchain", "crewai", "autogen", "ollama", "google-genai"]
        active_framework = None

        for fw in target_frameworks:
            if fw in self.directory_index:
                paths = self.directory_index[fw]
                valid_paths = [
                    p
                    for p in paths
                    if os.path.isdir(p) and "site-packages" in p.lower()
                ]
                if valid_paths:
                    injection_path = os.path.dirname(valid_paths[0])
                    import sys

                    if injection_path not in sys.path:
                        sys.path.append(injection_path)
                    active_framework = fw
                    print(
                        f"[Bullshit Builder - Scaffolder] 🎯 SUCCESS! Hijacked '{fw}' framework found on drive: {injection_path}"
                    )
                    break

        if not active_framework:
            print(
                "[Bullshit Builder - Scaffolder] No external frameworks found on drives. Falling back to native AI-BS GenAI router."
            )
            active_framework = "native-genai"

        return active_framework

    def execute_agent_build_workflow(
        self, human_idea: str, project_keyword: str
    ) -> str:
        potential_workspaces = self.discover_workspace(project_keyword)
        if not potential_workspaces:
            print(
                f"[Bullshit Builder - Scaffolder] No existing folder found for '{project_keyword}'. Defaulting to creating a new local workspace."
            )
            target_workspace = "./agent_workspace"
        else:
            print(
                f"[Bullshit Builder - Scaffolder] Found {len(potential_workspaces)} potential target paths on your system:"
            )
            for idx, path in enumerate(potential_workspaces):
                print(f"  [{idx}] {path}")
            target_workspace = potential_workspaces[0]
            if os.path.isfile(target_workspace):
                target_workspace = os.path.dirname(target_workspace)

        print(
            f"[Bullshit Builder - Scaffolder] AI Agent target directory set to: {target_workspace}"
        )
        active_framework = self._discover_and_load_llm_framework()

        agent_prompt = f"""
        Human Idea: {human_idea}
        Target Directory Context: {target_workspace}
        Active Framework Engine: {active_framework}
        
        You have direct access to system build tools. Generate the plan to inject code into this workspace.
        """

        print(
            f"[Bullshit Builder - Scaffolder] Ready to dispatch code building tools to target drive path: {target_workspace}"
        )
        print(
            f"[Bullshit Builder - Scaffolder] Routing prompt payload through {active_framework.upper()} wrapper..."
        )

        return target_workspace


if __name__ == "__main__":
    # If run directly, boot the refactoring daemon loop by default
    asyncio.run(refactoring_loop())
