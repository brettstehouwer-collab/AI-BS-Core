class UIGenerator:
    def __init__(self, frontend_components_dir: str = None):
        if frontend_components_dir:
            self.target_dir = frontend_components_dir
        else:
            self.target_dir = os.path.join(FRONTEND_SRC_DIR, "components")

        os.makedirs(self.target_dir, exist_ok=True)
        print(
            f"[Bullshit Builder - UI] Initialized. Target Directory: {self.target_dir}"
        )

    def _strip_markdown(self, raw_llm_output: str) -> str:
        stripped = re.sub(r"^```[a-zA-Z]*\n", "", raw_llm_output, flags=re.MULTILINE)
        stripped = re.sub(r"```$", "", stripped, flags=re.MULTILINE)
        return stripped.strip()

    def generate_component(
        self, human_idea: str, component_name: str, file_extension: str = ".jsx"
    ):
        print(
            f"\n[Bullshit Builder - UI] Initiating build sequence for: {component_name}{file_extension}"
        )
        print(f"[Bullshit Builder - UI] Human Idea: {human_idea}")

        simulated_llm_output = f"""```jsx
import React from 'react';

// Auto-Generated by Bullshit Builder
// Idea: {human_idea}

const {component_name} = () => {{
    return (
        <div className="p-6 bg-gray-900 text-white rounded-xl shadow-2xl">
            <h1 className="text-2xl font-bold tracking-tight">AI-BS Autonomous Component</h1>
            <p className="mt-2 text-gray-400">This UI was generated from the following prompt:</p>
            <blockquote className="mt-4 border-l-4 border-blue-500 pl-4 italic text-gray-300">
                "{human_idea}"
            </blockquote>
        </div>
    );
}};

export default {component_name};
```"""

        print(
            "[Bullshit Builder - UI] Received layout payload from Local LLM. Stripping markdown..."
        )
        clean_code = self._strip_markdown(simulated_llm_output)
        file_path = os.path.join(self.target_dir, f"{component_name}{file_extension}")

        print(f"[Bullshit Builder - UI] Writing raw code to disk: {file_path}")
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(clean_code)

        print("[Bullshit Builder - UI] ✅ Component Build Successful.")
        return file_path

    def mutate_app_jsx(
        self, tab_id: str, tab_name: str, component_name: str, component_code: str
    ):
        print(
            f"[Bullshit Builder - Mutator] Initiating Morphic AST Component Injection for {component_name}..."
        )

        if not os.path.exists(APP_JSX_PATH):
            print(f"[Bullshit Builder - Mutator] Error: {APP_JSX_PATH} not found.")
            return False

        backup_path = APP_JSX_PATH + ".bak"
        shutil.copy(APP_JSX_PATH, backup_path)
        print("[Bullshit Builder - Mutator] Safety backup created.")

        component_path = os.path.join(FRONTEND_SRC_DIR, f"{component_name}.jsx")
        with open(component_path, "w", encoding="utf-8") as f:
            f.write(component_code)
        print(
            f"[Bullshit Builder - Mutator] Hot-Reload Component Built: {component_name}.jsx"
        )

        try:
            with open(APP_JSX_PATH, "r", encoding="utf-8") as f:
                content = f.read()

            import_stmt = f"import {component_name} from './{component_name}';"
            if import_stmt not in content:
                imports = list(re.finditer(r"import\s+.*?;", content))
                if imports:
                    last_import = imports[-1]
                    insert_pos = last_import.end()
                    content = (
                        content[:insert_pos] + "\n" + import_stmt + content[insert_pos:]
                    )
                else:
                    last_import_idx = content.rfind("import ")
                    if last_import_idx != -1:
                        end_of_line = content.find("\n", last_import_idx)
                        content = (
                            content[: end_of_line + 1]
                            + import_stmt
                            + "\n"
                            + content[end_of_line + 1 :]
                        )
                    else:
                        content = import_stmt + "\n" + content

            tab_entry = (
                f"{{ id: '{tab_id}', name: '{tab_name}', component: {component_name} }}"
            )
            if tab_entry not in content:
                tabs_match = re.search(r"const\s+tabs\s*=\s*\[", content)
                if tabs_match:
                    start_idx = tabs_match.end()
                    bracket_count = 1
                    end_idx = start_idx
                    while bracket_count > 0 and end_idx < len(content):
                        if content[end_idx] == "[":
                            bracket_count += 1
                        elif content[end_idx] == "]":
                            bracket_count -= 1
                        end_idx += 1
                    insert_idx = end_idx - 1
                    content = (
                        content[:insert_idx]
                        + f",\n      {tab_entry}\n  "
                        + content[insert_idx:]
                    )
                else:
                    tabs_idx = content.find("const tabs = [")
                    if tabs_idx != -1:
                        bracket_end = content.find("]", tabs_idx)
                        last_comma = content.rfind("\n", tabs_idx, bracket_end)
                        content = (
                            content[:last_comma]
                            + f"\n      {tab_entry},"
                            + content[last_comma:]
                        )

            with open(APP_JSX_PATH, "w", encoding="utf-8") as f:
                f.write(content)

            print(
                "[Bullshit Builder - Mutator] Morphic AST Injection Complete. Initiating Sandbox Build Check..."
            )

            frontend_dir = os.path.dirname(FRONTEND_SRC_DIR)
            build_result = subprocess.run(
                ["npm", "run", "build"],
                cwd=frontend_dir,
                capture_output=True,
                text=True,
                shell=False,
            )

            if build_result.returncode != 0:
                raise Exception(
                    f"React Compilation Failed:\n{build_result.stderr or build_result.stdout}"
                )

            print(
                "[Bullshit Builder - Mutator] Sandbox Build Check Passed. App compiles perfectly."
            )
            return True

        except Exception as e:
            print(
                f"[Bullshit Builder - Mutator] Critical Error during Mutation/Compilation: {e}"
            )
            print("[Bullshit Builder - Mutator] Rolling back to safe state...")
            if os.path.exists(backup_path):
                shutil.copy(backup_path, APP_JSX_PATH)
            if os.path.exists(component_path):
                os.remove(component_path)
            return False


def inject_ui_tab(
    component_name: str, tab_id: str, tab_name: str, component_code: str
) -> bool:
    generator = UIGenerator()
    return generator.mutate_app_jsx(tab_id, tab_name, component_name, component_code)


