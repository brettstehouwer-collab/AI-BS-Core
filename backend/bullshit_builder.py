BACKEND_DIR = os.path.dirname(__file__)
FRONTEND_SRC_DIR = os.path.join(os.path.dirname(BACKEND_DIR), "frontend", "src")
APP_JSX_PATH = os.path.join(FRONTEND_SRC_DIR, "App.jsx")


async def analyze_and_refactor(file_path):
    print(
        f"[Bullshit Builder - Refactoring] Analyzing Time/Space Complexity for: {os.path.basename(file_path)}"
    )
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            code = f.read()

        prompt = (
            "You are the Refactoring Daemon. Analyze this code for Big O time/space complexity and bloated logic.\n"
            "If it is highly optimized, reply 'OPTIMIZED'.\n"
            "If you can rewrite it to be significantly faster or cleaner, output ONLY the fully refactored Python or React code, wrapped in ``` markdown blocks.\n\n"
            f"Code:\n{code[:3000]}"
        )

        async with httpx.AsyncClient() as client:
            r = await client.post(
                "http://127.0.0.1:11434/api/generate",
                json={"model": "stehouwer_llm", "prompt": prompt, "stream": False},
                timeout=60.0,
            )

            if r.status_code == 200:
                response = r.json().get("response", "").strip()
                if "OPTIMIZED" not in response and len(response) > 50:
                    import re

                    match = re.search(
                        r"```(?:python|javascript|jsx)?(.*?)```", response, re.DOTALL
                    )
                    if match:
                        clean_code = match.group(1).strip()
                    else:
                        print(
                            f"[Bullshit Builder - Refactoring] LLM output invalid (no code block). Skipping mutation."
                        )
                        return

                    print(
                        f"[Bullshit Builder - Refactoring] Faster implementation found for {os.path.basename(file_path)}! Mutation disabled for safety."
                    )
                else:
                    print(f"[Bullshit Builder - Refactoring] Code is already optimal.")
    except Exception as e:
        print(f"[Bullshit Builder - Refactoring] Failed to analyze {file_path}: {e}")


async def sweep_directories():
    py_files = glob.glob(os.path.join(BACKEND_DIR, "*.py"))
    jsx_files = glob.glob(os.path.join(FRONTEND_SRC_DIR, "*.jsx"))

    import random

    all_files = py_files + jsx_files
    if not all_files:
        return

    target = random.choice(all_files)
    await analyze_and_refactor(target)


async def refactoring_loop():
    print(
        "[Bullshit Builder - Refactoring] Booted. Utilizing idle threads for continuous code optimization."
    )
    while True:
        await sweep_directories()
        await asyncio.sleep(120)


